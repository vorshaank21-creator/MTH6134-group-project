# first data set
league_players= read.csv("league_players.csv")
x= lm(bmi~age, data=league_players)
summary(x)
plot(x)
stdres= rstandard(x)
fits= fitted(x)
plot(fits, stdres, main= "std residuals versus fits")
qqnorm(stdres, main= "qq_plot_x")
qqline(stdres)

